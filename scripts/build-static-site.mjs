#!/usr/bin/env node
/**
 * Assemble the static student site (.static-site/) from a finished
 * `opennextjs-cloudflare build`.
 *
 * The student pages are prerendered by Next.js, so they are served as plain
 * files from Cloudflare's CDN: no Worker runs, no CPU limit applies, and the
 * requests don't count against the Workers plan. Only the admin console runs
 * as a Worker (wrangler.jsonc).
 *
 * Their Content-Security-Policy can't use a per-request nonce, so this script
 * hashes every inline <script> in the built pages and writes the policy, plus
 * the security and cache headers next.config.ts would have added, to _headers.
 */
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// The same policy builder the app uses (Node runs the TypeScript directly)
import { siteCsp } from "../src/lib/csp.ts";

const ROOT = new URL("..", import.meta.url).pathname;
const OUT = join(ROOT, ".static-site");
const APP = join(ROOT, ".next/server/app");
const ASSETS = join(ROOT, ".open-next/assets");

// Prerendered page -> path it is served at (html_handling: auto-trailing-slash)
const PAGES = {
  "index.html": "index.html",
  "weekly.html": "weekly.html",
  "daily.html": "daily.html",
  "static-404.html": "404.html",
};

function fail(message) {
  console.error(`build-static-site: ${message}`);
  process.exit(1);
}

if (!existsSync(ASSETS)) fail("run `opennextjs-cloudflare build` first (.open-next/assets is missing)");

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
cpSync(ASSETS, OUT, { recursive: true });

const hashes = new Set();
const INLINE_SCRIPT = /<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi;

for (const [source, target] of Object.entries(PAGES)) {
  const file = join(APP, source);
  if (!existsSync(file)) fail(`${source} was not prerendered - is a student page dynamic again?`);
  const html = readFileSync(file, "utf8");
  if (html.includes('nonce="')) fail(`${source} carries a nonce; student pages must render statically`);
  for (const match of html.matchAll(INLINE_SCRIPT)) {
    if (!match[1]) continue;
    hashes.add(`sha256-${createHash("sha256").update(match[1], "utf8").digest("base64")}`);
  }
  writeFileSync(join(OUT, target), html);
}

const apiBase = process.env.NEXT_PUBLIC_API_BASE_URL;
if (!apiBase) fail("NEXT_PUBLIC_API_BASE_URL is not set");

const csp = siteCsp({
  scriptHashes: [...hashes].sort(),
  isDev: false,
  upgradeInsecure: true,
  apiOrigin: new URL(apiBase).origin,
  firebaseAuthDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN ?? "",
  userbackEnabled: Boolean(process.env.NEXT_PUBLIC_USERBACK_TOKEN),
});

// Header values joined by Cloudflare when several rules match, so each header
// is set by exactly one rule
const headers = `# Generated by scripts/build-static-site.mjs - do not edit
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=63072000; includeSubDomains; preload
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(self), display-capture=(self), geolocation=(), payment=(), usb=(), interest-cohort=()
  Cross-Origin-Opener-Policy: same-origin-allow-popups
  Cross-Origin-Resource-Policy: same-origin
  X-DNS-Prefetch-Control: off

/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

/avatars/*
  Cache-Control: public, max-age=86400, stale-while-revalidate=604800

/images/*
  Cache-Control: public, max-age=86400, stale-while-revalidate=604800
`;
writeFileSync(join(OUT, "_headers"), headers);

console.log(`build-static-site: ${Object.keys(PAGES).length} pages, ${hashes.size} inline script hashes -> .static-site/`);
